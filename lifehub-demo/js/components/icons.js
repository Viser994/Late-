/** Render an SVG icon with optional size class */
export function icon(name, className = "icon") {
  const svg = ICONS[name] || ICONS.doc;
  return `<span class="${className}" aria-hidden="true">${svg}</span>`;
}

/** Life Pulse ring SVG — animated score visualization */
export function lifePulseRing(score, size = 160) {
  const radius = (size - 16) / 2;
  const circumference = 2 * Math.PI * radius;
  const offset = circumference - (score / 100) * circumference;
  const color = score >= 80 ? "#22c55e" : score >= 50 ? "#f59e0b" : "#ef4444";
  const cx = size / 2;
  const cy = size / 2;

  return `
    <svg class="life-pulse__ring" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
      <defs>
        <linearGradient id="pulse-grad" x1="0%" y1="0%" x2="100%" y2="100%">
          <stop offset="0%" stop-color="${color}" stop-opacity="0.3"/>
          <stop offset="100%" stop-color="${color}" stop-opacity="0.05"/>
        </linearGradient>
      </defs>
      <circle cx="${cx}" cy="${cy}" r="${radius}" fill="url(#pulse-grad)" />
      <circle cx="${cx}" cy="${cy}" r="${radius}" fill="none" stroke="var(--border-color)" stroke-width="6" />
      <circle
        class="life-pulse__progress"
        cx="${cx}" cy="${cy}" r="${radius}"
        fill="none"
        stroke="${color}"
        stroke-width="6"
        stroke-linecap="round"
        stroke-dasharray="${circumference}"
        stroke-dashoffset="${offset}"
        transform="rotate(-90 ${cx} ${cy})"
      />
      <text x="${cx}" y="${cy - 6}" text-anchor="middle" class="life-pulse__score" fill="var(--text-primary)">${score}</text>
      <text x="${cx}" y="${cy + 14}" text-anchor="middle" class="life-pulse__label" fill="var(--text-secondary)">Life Pulse</text>
    </svg>
  `;
}
